#!/usr/bin/env bash

# Включаем строгий режим: скрипт упадет при критической ошибке
set -e

# ==================== КОНФИГУРАЦИЯ ====================
# Имя удаляемого сервиса (должно строго совпадать с именем в скрипте создания)
SERVICE_NAME="SimpleSwitcher.service"
# ======================================================

TARGET_PATH="/etc/systemd/system/$SERVICE_NAME"

# 1. Проверяем, существует ли вообще такой сервис
if [ ! -f "$TARGET_PATH" ]; then
    echo "Предупреждение: Сервис $SERVICE_NAME не найден в системе (возможно, уже удален)."
    exit 0
fi

echo "Начинаем полное удаление сервиса $SERVICE_NAME..."

# 2. Останавливаем запущенный процесс
echo "Останавливаем сервис..."
sudo systemctl stop "$SERVICE_NAME" || echo "Сервис уже был остановлен."

# 3. Убираем сервис из автозагрузки системы
echo "Удаляем из автозагрузки..."
sudo systemctl disable "$SERVICE_NAME" || echo "Сервис не был в автозагрузке."

# 4. Удаляем сам конфигурационный файл юнита
echo "Удаляем файл конфигурации..."
sudo rm -f "$TARGET_PATH"

# 5. Очищаем символические ссылки, которые могли остаться в systemd
sudo rm -f "/etc/systemd/system/multi-user.target.wants/$SERVICE_NAME"

# 6. Заставляем systemd полностью стереть информацию о сервисе из памяти
echo "Перезагружаем демона systemd для очистки кэша..."
sudo systemctl daemon-reload
sudo systemctl reset-failed || true

echo "Удаление завершено! Сервис полностью очищен из системы."
